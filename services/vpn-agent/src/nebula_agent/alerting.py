"""Sending an alert somewhere a person will actually see it.

Deliberately standalone: it POSTs to Resend over HTTPS with nothing but the
standard library, and shares no process, container or database with the thing
it reports on. An alerter that needs the API container up cannot tell you the
API container is down, which is the message most worth receiving.

It reuses Resend because the app already sends through it, so SPF and DKIM for
this domain are already correct and the mail is already unlikely to be
filtered. See docs/runbooks/mail-authentication.md.
"""

import json
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path

from nebula_agent import __version__

_RESEND_ENDPOINT = "https://api.resend.com/emails"

# Resend sits behind Cloudflare, which blocks urllib's default
# "Python-urllib/x.y" User-Agent outright with a generic 403 and no
# application-level detail. The worker's adapter hit this against a real
# deployment; any identifying value avoids it.
_USER_AGENT = f"nebula-agent/{__version__}"

_TIMEOUT_SECONDS = 15.0


class AlertNotSent(Exception):
    """The alert could not be delivered.

    Raised rather than swallowed: a health check that cannot report is itself
    a fault, and one that fails silently leaves the deployment looking
    monitored while nothing is watching.
    """


@dataclass(frozen=True, slots=True)
class Mailer:
    api_key: str
    sender: str
    recipient: str

    @classmethod
    def from_files(cls, api_key_file: Path, sender: str, recipient: str) -> "Mailer":
        try:
            api_key = api_key_file.read_text(encoding="utf-8").strip()
        except OSError as error:
            raise AlertNotSent(f"could not read {api_key_file}") from error
        if not api_key:
            raise AlertNotSent(f"{api_key_file} is empty")
        return cls(api_key=api_key, sender=sender, recipient=recipient)

    def send(self, *, subject: str, body: str) -> str:
        payload = json.dumps(
            {
                "from": self.sender,
                "to": [self.recipient],
                "subject": subject,
                "text": body,
            }
        ).encode("utf-8")
        request = urllib.request.Request(
            _RESEND_ENDPOINT,
            data=payload,
            method="POST",
            headers={
                "Authorization": f"Bearer {self.api_key}",
                "Content-Type": "application/json",
                "User-Agent": _USER_AGENT,
            },
        )
        try:
            with urllib.request.urlopen(request, timeout=_TIMEOUT_SECONDS) as response:  # noqa: S310
                decoded = json.loads(response.read())
        except (urllib.error.URLError, TimeoutError, OSError) as error:
            raise AlertNotSent("Resend delivery failed") from error
        except json.JSONDecodeError as error:
            raise AlertNotSent("Resend response was not JSON") from error
        message_id = decoded.get("id") if isinstance(decoded, dict) else None
        if not isinstance(message_id, str):
            raise AlertNotSent("Resend response carried no message id")
        return message_id


# Short. This runs inside the health check, and a monitoring ping that hangs
# would delay the checks it is reporting on.
_PING_TIMEOUT_SECONDS = 10.0


def ping_dead_man_switch(url: str, *, healthy: bool) -> None:
    """Tell an outside service this host is alive, or that it is not.

    Everything else here reports *from* the VPS, which means none of it can
    report the VPS being gone. Power loss, a network partition, a kernel panic,
    the host being suspended for an unpaid invoice: in every one of those the
    alerter dies with the thing it was watching, and the result is silence that
    looks exactly like health.

    An outside service that expects to hear from us on a schedule is the only
    shape that covers this, because the alert is generated by the absence of a
    message rather than the presence of one.

    `healthy=False` posts to the failure path, so the external service alerts
    too when the checks fail. That is duplication with the email on purpose:
    the case worth covering is Resend being down, or the API key being wrong,
    or the mail silently landing in spam -- exactly when the primary path is
    the thing that is broken.

    Never raises. The caller is a health check in the middle of reporting real
    problems, and failing it over an unreachable monitoring service would
    suppress the alert that mattered. It also needs no error path of its own:
    if these pings stop arriving, the external service says so, which is the
    whole point.
    """

    target = url if healthy else f"{url.rstrip('/')}/fail"
    # The URL comes from this host's own configuration file, not from anything
    # the network said, so the scheme is the operator's choice. Rejected
    # outright rather than trusted blindly all the same: a file: or custom
    # scheme here would be a misconfiguration that silently stopped pinging,
    # and a switch that is not pinging looks identical to a dead host.
    if not target.startswith(("https://", "http://")):
        return
    request = urllib.request.Request(  # noqa: S310 - scheme checked immediately above
        target, method="GET", headers={"User-Agent": _USER_AGENT}
    )
    try:
        with urllib.request.urlopen(  # noqa: S310 - scheme checked above
            request, timeout=_PING_TIMEOUT_SECONDS
        ):
            pass
    except (urllib.error.URLError, TimeoutError, OSError, ValueError):
        # Deliberately not re-raised and deliberately not logged with the URL:
        # a ping URL is a capability, and anyone holding it can keep the switch
        # alive while the host is dead.
        return
